for locale in sorted(os.listdir(locales_dir)):
    filepath = os.path.join(locales_dir, locale, 'messages.json')
    if not os.path.exists(filepath):
        continue
    with open(filepath, encoding='utf-8') as f:
        data = json.load(f)
    
    # Rebuild the dict with new keys inserted after settings.i18n.title
    new_data = {}
    for key, value in data.items():
        new_data[key] = value
        if key == 'settings.i18n.title':
            new_data['settings.title'] = chat_title_translations.get(locale, 'Settings')
            new_data['settings.subtitle'] = subtitle_translations.get(locale, 'Manage your account preferences and security.')
            new_data['settings.uuid_label'] = uuid_label_translations.get(locale, 'UUID:')
            new_data['settings.section_personal'] = section_personal_translations.get(locale, 'Personal Details')
            new_data['settings.section_appearance'] = section_appearance_translations.get(locale, 'Appearance')
            new_data['settings.section_security'] = section_security_translations.get(locale, 'Security')
            new_data['settings.section_passkeys'] = section_passkeys_translations.get(locale, 'Passkeys')
            new_data['settings.section_ai'] = section_ai_translations.get(locale, 'AI Keys')
            new_data['settings.section_language'] = section_language_translations.get(locale, 'Language')
            new_data['settings.appearance_desc'] = appearance_desc_translations.get(locale, 'Customize your app theme and UI style.')
            new_data['settings.border_style'] = border_style_translations.get(locale, 'Border Style')
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f'{locale}: Added settings keys')

print('Done!')
